/**
 * UseCase1HotelBookingApp
 *
 * This class represents the entry point of the Hotel Booking application.
 * It demonstrates how a Java application starts execution using the main()
 * method and prints a welcome message to the console.
 *
 * The program displays the application name and version information.
 *
 * @author Student
 * @version 1.0
 */

public class BookMyStayApp {

    /**
     * The main method is the entry point of the Java application.
     * The JVM invokes this method when the program is executed.
     *
     * @param args Command line arguments passed to the program
     */
    public static void main(String[] args) {

        // Print welcome message
        System.out.println("=================================");
        System.out.println("   Welcome to Hotel Booking App  ");
        System.out.println("=================================");

        // Display application name and version
        System.out.println("Application: Hotel Booking System");
        System.out.println("Version: 1.0");

        // End message
        System.out.println("Application started successfully.");
        System.out.println("Thank you for using the system!");
    }
}